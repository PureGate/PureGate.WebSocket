using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Schema;
using System.Text.Json.Serialization.Metadata;
using PureGate.WebSocket.Serialization;

namespace PureGate.WebSocket.Contracts;

// One operation, stream or event in the contract. A stream's Response is its item type; an upload has an Item type
// besides its Request and Response, and the others have none.
readonly record struct ContractMember(string Section, string Name, Type Request, Type Response, Type Item = null);

// Writes an endpoint's members as TypeScript (docs/PLAN-SERVER.md, Contract generation). JsonSchemaExporter describes
// each type from the serializer's own metadata; a transform marks the object types, which become named interfaces.
// The hash covers a canonical form of those schemas, not the TypeScript text.
sealed class ContractGenerator
{
  // Marks a schema node as a named type, with the type's key, until the names are known.
  const string TypeKey = "$pgType";

  // Marks a property the serializer may leave out.
  const string OptionalKey = "$pgOptional";

  // Replaces a schema with TypeScript the app chose (ContractOptions.MapType).
  const string OverrideKey = "$pgTypeScript";

  // Adds a note to a property's documentation.
  const string NoteKey = "$pgNote";

  static readonly string[] Sections = ["api", "streams", "uploads", "events", "clientApi", "clientEvents"];

  // Names a generated interface must not take: they would hide the globals the contract uses, or its own exports.
  static readonly HashSet<string> Reserved = new(StringComparer.Ordinal)
  {
    "Array", "BigInt", "Boolean", "Contract", "Date", "Error", "Function", "Map", "Number", "Object", "Promise",
    "Record", "Set", "String", "Symbol", "Uint8Array", "contractHash",
  };

  readonly JsonSerializerOptions Serializer;
  readonly ContractOptions Options;
  readonly Dictionary<string, Type> Types = new(StringComparer.Ordinal);
  readonly Dictionary<string, JsonObject> Definitions = new(StringComparer.Ordinal);
  readonly Dictionary<string, int> DefinitionDepths = new(StringComparer.Ordinal);
  Dictionary<string, string> Names;

  ContractGenerator(JsonSerializerOptions serializer, ContractOptions options)
  {
    Serializer = serializer;
    Options = options;
  }

  public static WebSocketContract Generate(
      string route,
      IEnumerable<ContractMember> members,
      JsonSerializerOptions serializer,
      ContractOptions options)
  {
    var generator = new ContractGenerator(serializer, options);
    return generator.Run(route, [.. members.OrderBy(member => Array.IndexOf(Sections, member.Section)).ThenBy(member => member.Name, StringComparer.Ordinal)]);
  }

  WebSocketContract Run(string route, ContractMember[] members)
  {
    // Every payload's schema first: exporting them is what finds the named types.
    var payloads = members
      .Select(member => (Request: Export(member.Request), Response: Export(member.Response), Item: member.Item is null ? null : Export(member.Item)))
      .ToArray();
    Names = AssignNames();

    var hash = Hash(members, payloads);
    var typeScript = new StringBuilder();
    typeScript.Append(CultureInfo, $"// Generated by PureGate.WebSocket from {route}. Contract {hash}.\n");
    typeScript.Append("// Do not edit: pull it again from the server when its operations change.\n\n");

    foreach (var (key, name) in Names.OrderBy(pair => pair.Value, StringComparer.Ordinal))
      WriteDefinition(typeScript, name, Definitions[key]);

    WriteContract(typeScript, members, payloads);
    typeScript.Append(CultureInfo, $"\nexport const contractHash = \"{hash}\";\n");
    return new WebSocketContract(typeScript.ToString(), hash);
  }

  static IFormatProvider CultureInfo => System.Globalization.CultureInfo.InvariantCulture;

  // The schema of a payload type, or null for one that is not JSON: nothing, or raw bytes.
  JsonNode Export(Type type)
  {
    if (type == typeof(NoPayload) || IsBinary(type))
      return null;

    var root = JsonSchemaExporter.GetJsonSchemaAsNode(Serializer.GetTypeInfo(type), new JsonSchemaExporterOptions
    {
      TreatNullObliviousAsNonNullable = !Options.ReferenceTypesCanBeNull,
      TransformSchemaNode = Transform,
    });

    // The exporter writes parts of a schema that repeat as JSON pointers to their first occurrence in this document.
    Resolve(root, root, depth: 0);
    return root;
  }

  JsonNode Transform(JsonSchemaExporterContext context, JsonNode node)
  {
    var type = context.TypeInfo.Type;
    if (Options.Overrides.TryGetValue(type, out var typeScript))
      return new JsonObject { [OverrideKey] = typeScript };
    if (node is not JsonObject schema)
      return node;

    if (context.PropertyInfo is { ShouldSerialize: not null })
      schema[OptionalKey] = true;
    if (type == typeof(long) || type == typeof(ulong))
      schema[NoteKey] = "A 64-bit integer: exact in JavaScript up to 2^53.";

    // The exporter marks reference types as nullable unless their annotations say otherwise, and code without
    // nullable annotations says nothing. Only Nullable<T> keeps its null, unless the app asked for reference types.
    if (!Options.ReferenceTypesCanBeNull && !type.IsValueType && schema["type"] is JsonArray types)
    {
      var kept = types.Select(item => item?.GetValue<string>()).Where(name => name != "null").ToArray();
      schema["type"] = kept.Length == 1 ? JsonValue.Create(kept[0]) : new JsonArray([.. kept.Select(name => (JsonNode)JsonValue.Create(name))]);
    }

    if (context.TypeInfo.Kind == JsonTypeInfoKind.Object && (schema.ContainsKey("properties") || schema.ContainsKey("anyOf")))
    {
      var key = type.FullName ?? type.Name;
      Types.TryAdd(key, type);
      schema[TypeKey] = key;

      // The shallowest occurrence, which the exporter wrote with the fewest pointers.
      var depth = context.Path.Length;
      if (!DefinitionDepths.TryGetValue(key, out var known) || depth < known)
      {
        Definitions[key] = schema;
        DefinitionDepths[key] = depth;
      }
    }

    return node;
  }

  // Replaces every JSON pointer under node: one to a named type with a reference to its name, and one to anything
  // else with a copy of what it points at. A type only contains itself through a named type, so copying ends; the
  // depth limit guards against one that does not.
  static JsonNode Resolve(JsonNode node, JsonNode root, int depth)
  {
    switch (node)
    {
      case JsonObject schema when schema["$ref"] is JsonValue pointer:
        var target = depth > 32 ? null : Navigate(root, pointer.GetValue<string>());
        JsonObject replacement;
        if (target is JsonObject named && named[TypeKey] is JsonValue key)
        {
          replacement = new JsonObject { [TypeKey] = key.GetValue<string>() };
          if (named["type"] is { } types)
            replacement["type"] = types.DeepClone();
        }
        else
        {
          replacement = target is JsonObject unnamed ? (JsonObject)Resolve(unnamed.DeepClone(), root, depth + 1) : new JsonObject();
        }

        foreach (var marker in (ReadOnlySpan<string>)[OptionalKey, NoteKey])
        {
          if (schema[marker] is { } value)
            replacement[marker] = value.DeepClone();
        }

        return replacement;

      case JsonObject schema:
        foreach (var (name, value) in schema.ToArray())
        {
          if (value is not null && Resolve(value, root, depth) is var resolved && !ReferenceEquals(resolved, value))
            schema[name] = resolved;
        }

        return schema;

      case JsonArray items:
        for (var i = 0; i < items.Count; i++)
        {
          if (items[i] is { } item && Resolve(item, root, depth) is var resolved && !ReferenceEquals(resolved, item))
            items[i] = resolved;
        }

        return items;

      default:
        return node;
    }
  }

  static JsonNode Navigate(JsonNode root, string pointer)
  {
    if (pointer == "#")
      return root;

    var node = root;
    foreach (var part in pointer.TrimStart('#').TrimStart('/').Split('/'))
    {
      var token = part.Replace("~1", "/", StringComparison.Ordinal).Replace("~0", "~", StringComparison.Ordinal);
      node = node switch
      {
        JsonObject schema => schema[token],
        JsonArray items when int.TryParse(token, CultureInfo, out var index) => items[index],
        _ => null,
      };
    }

    return node;
  }

  // Interfaces take their .NET names: Page<Order> is PageOfOrder. Names two types share gain namespace segments
  // until they differ.
  Dictionary<string, string> AssignNames()
  {
    var names = new Dictionary<string, string>(StringComparer.Ordinal);
    foreach (var group in Types.OrderBy(pair => pair.Key, StringComparer.Ordinal).GroupBy(pair => BaseName(pair.Value)))
    {
      var types = group.ToArray();
      for (var depth = 0; ; depth++)
      {
        var candidates = types.Select(pair => (pair.Key, Name: Qualified(pair.Value, group.Key, depth))).ToArray();
        if (types.Length == 1 || candidates.Select(candidate => candidate.Name).Distinct(StringComparer.Ordinal).Count() == types.Length || depth > 16)
        {
          foreach (var (key, name) in candidates)
            names[key] = Reserved.Contains(name) ? $"{name}_" : name;
          break;
        }
      }
    }

    return names;
  }

  static string Qualified(Type type, string baseName, int depth)
  {
    if (depth == 0)
      return baseName;

    var segments = (type.Namespace ?? "").Split('.', StringSplitOptions.RemoveEmptyEntries);
    return string.Concat(segments.TakeLast(depth)) + baseName;
  }

  static string BaseName(Type type)
  {
    var name = type.Name;
    var tick = name.IndexOf('`', StringComparison.Ordinal);
    if (tick >= 0)
      name = name[..tick];

    name = new string([.. name.Where(char.IsAsciiLetterOrDigit)]);
    if (type.IsGenericType)
      name += "Of" + string.Join("And", type.GetGenericArguments().Select(BaseName));

    return name.Length == 0 || char.IsAsciiDigit(name[0]) ? $"T{name}" : name;
  }

  void WriteDefinition(StringBuilder typeScript, string name, JsonObject schema)
  {
    if (!schema.ContainsKey("properties") && schema["anyOf"] is JsonArray variants)
    {
      typeScript.Append(CultureInfo, $"export type {name} = {Union(variants.Select(TypeOf))};\n\n");
      return;
    }

    typeScript.Append(CultureInfo, $"export interface {name} {{\n");
    if (schema["properties"] is JsonObject properties)
    {
      foreach (var (property, value) in properties)
      {
        if (Note(value) is { } note)
          typeScript.Append(CultureInfo, $"  /** {note} */\n");

        var optional = value is JsonObject propertySchema && propertySchema[OptionalKey] is JsonValue flag && flag.GetValue<bool>();
        typeScript.Append(CultureInfo, $"  {PropertyName(property)}{(optional ? "?" : "")}: {TypeOf(value)};\n");
      }
    }

    typeScript.Append("}\n\n");
  }

  static string Note(JsonNode value)
  {
    if (value is not JsonObject schema)
      return null;
    if (schema[NoteKey] is JsonValue note)
      return note.GetValue<string>();
    if (schema["format"] is JsonValue format)
      return format.GetValue<string>();
    return null;
  }

  // The TypeScript type a schema describes. A named type is referred to by name.
  string TypeOf(JsonNode node)
  {
    if (node is not JsonObject schema)
      return node is JsonValue value && value.TryGetValue(out bool allowed) && !allowed ? "never" : "unknown";

    if (schema[OverrideKey] is JsonValue typeScript)
      return typeScript.GetValue<string>();
    if (schema[TypeKey] is JsonValue key)
      return AllowsNull(schema) ? $"{Names[key.GetValue<string>()]} | null" : Names[key.GetValue<string>()];
    return Describe(schema);
  }

  // A schema that is not a named type.
  string Describe(JsonObject schema)
  {
    if (schema["const"] is { } constant)
      return Literal(constant);
    if (schema["enum"] is JsonArray values)
      return Union(values.Select(Literal));
    if ((schema["anyOf"] ?? schema["oneOf"]) is JsonArray variants)
      return Union(variants.Select(TypeOf));

    var types = schema["type"] switch
    {
      JsonValue single => [single.GetValue<string>()],
      JsonArray many => many.Select(type => type.GetValue<string>()).ToArray(),
      _ => schema.ContainsKey("properties") ? ["object"] : [],
    };
    if (types.Length == 0)
      return "unknown";

    // A number the serializer also reads from a string (JsonNumberHandling.AllowReadingFromString, as the Web defaults
    // do) is still written as a number, and browsers should send numbers.
    if (types.Any(type => type is "integer" or "number"))
      types = [.. types.Where(type => type != "string")];

    return Union(types.Select(type => type switch
    {
      "string" => "string",
      "integer" or "number" => "number",
      "boolean" => "boolean",
      "null" => "null",
      "array" => $"{Wrap(schema["items"] is { } items ? TypeOf(items) : "unknown")}[]",
      "object" => DescribeObject(schema),
      _ => "unknown",
    }));
  }

  string DescribeObject(JsonObject schema)
  {
    if (schema["properties"] is JsonObject properties && properties.Count > 0)
      return $"{{ {string.Join(" ", properties.Select(pair => $"{PropertyName(pair.Key)}: {TypeOf(pair.Value)};"))} }}";

    return schema["additionalProperties"] is JsonObject values ? $"Record<string, {TypeOf(values)}>" : "Record<string, unknown>";
  }

  static bool AllowsNull(JsonObject schema) => schema["type"] is JsonArray types && types.Any(type => type?.GetValue<string>() == "null");

  static string Union(IEnumerable<string> types)
  {
    var distinct = types.Distinct(StringComparer.Ordinal).ToArray();
    return distinct.Length == 0 ? "never" : string.Join(" | ", distinct);
  }

  static string Wrap(string type) => type.Contains(' ', StringComparison.Ordinal) ? $"({type})" : type;

  static string Literal(JsonNode value) => value?.ToJsonString() ?? "null";

  static string PropertyName(string name) =>
    name.Length > 0 && (char.IsAsciiLetter(name[0]) || name[0] is '_' or '$') && name.All(c => char.IsAsciiLetterOrDigit(c) || c is '_' or '$')
      ? name
      : JsonSerializer.Serialize(name, HandshakeJson.Default.String);

  void WriteContract(StringBuilder typeScript, ContractMember[] members, (JsonNode Request, JsonNode Response, JsonNode Item)[] payloads)
  {
    typeScript.Append("export interface Contract {\n");
    foreach (var section in Sections)
    {
      var tree = new Group();
      for (var i = 0; i < members.Length; i++)
      {
        if (members[i].Section == section)
          tree.Add(members[i].Name, Signature(members[i], payloads[i]));
      }

      if (!tree.IsEmpty)
        tree.Write(typeScript, section, "  ");
    }

    typeScript.Append("}\n");
  }

  string Signature(ContractMember member, (JsonNode Request, JsonNode Response, JsonNode Item) payload)
  {
    var leaf = member.Name[(member.Name.LastIndexOf('.') + 1)..];
    var isEvent = member.Section is "events" or "clientEvents";
    var parameters = new List<string>(2);
    if (member.Request != typeof(NoPayload))
      parameters.Add($"{(isEvent ? "event" : "request")}: {PayloadType(member.Request, payload.Request)}");
    if (member.Item is not null)
      parameters.Add($"item: {PayloadType(member.Item, payload.Item)}");

    var result = isEvent ? "void" : PayloadType(member.Response, payload.Response);
    return $"{leaf}({string.Join(", ", parameters)}): {result};";
  }

  string PayloadType(Type type, JsonNode schema) =>
    type == typeof(NoPayload) ? "void" : IsBinary(type) ? "Uint8Array" : TypeOf(schema);

  static bool IsBinary(Type type) => type == typeof(byte[]) || type == typeof(ReadOnlyMemory<byte>);

  // A hash of what the contract means: every member's payload schemas and every named type's schema, in a
  // canonical form with sorted keys and named types referred to by their TypeScript names.
  string Hash(ContractMember[] members, (JsonNode Request, JsonNode Response, JsonNode Item)[] payloads)
  {
    var model = new JsonObject();
    var memberModels = new JsonObject();
    for (var i = 0; i < members.Length; i++)
    {
      var member = new JsonArray(
        CanonicalPayload(members[i].Request, payloads[i].Request),
        CanonicalPayload(members[i].Response, payloads[i].Response));
      if (members[i].Item is not null)
        member.Add(CanonicalPayload(members[i].Item, payloads[i].Item));

      memberModels[$"{members[i].Section}:{members[i].Name}"] = member;
    }

    var types = new JsonObject();
    foreach (var (key, name) in Names)
      types[name] = Canonical(Definitions[key], definition: true);

    model["members"] = memberModels;
    model["types"] = types;

    var buffer = new System.Buffers.ArrayBufferWriter<byte>();
    using (var writer = new Utf8JsonWriter(buffer))
      WriteSorted(writer, model);

    return Convert.ToHexStringLower(SHA256.HashData(buffer.WrittenSpan))[..16];
  }

  JsonNode CanonicalPayload(Type type, JsonNode schema) =>
    type == typeof(NoPayload) ? JsonValue.Create("void") : IsBinary(type) ? JsonValue.Create("binary") : Canonical(schema, definition: false);

  // The keywords that shape the TypeScript. Others, such as pattern and required, vary between .NET versions
  // without changing the contract, so they stay out of the hash.
  static readonly HashSet<string> Meaningful = new(StringComparer.Ordinal)
  {
    "type", "properties", "items", "additionalProperties", "enum", "const", "anyOf", "oneOf", "format",
    OptionalKey, OverrideKey, NoteKey,
  };

  JsonNode Canonical(JsonNode node, bool definition)
  {
    switch (node)
    {
      case JsonObject schema when !definition && schema[TypeKey] is JsonValue key:
        return new JsonObject { ["$name"] = Names[key.GetValue<string>()], ["null"] = AllowsNull(schema) };
      case JsonObject schema:
        var copy = new JsonObject();
        foreach (var (name, value) in schema)
        {
          if (!Meaningful.Contains(name) || value is null || (name == "additionalProperties" && value is not JsonObject))
            continue;

          copy[name] = name == "type" && value is JsonArray types
            ? new JsonArray([.. types.Select(type => type?.GetValue<string>()).Order(StringComparer.Ordinal).Select(type => (JsonNode)JsonValue.Create(type))])
            : name == "properties" && value is JsonObject properties
              ? new JsonObject(properties.Select(pair => KeyValuePair.Create(pair.Key, pair.Value is null ? null : Canonical(pair.Value, definition: false))))
              : Canonical(value, definition: false);
        }

        return copy;
      case JsonArray items:
        return new JsonArray([.. items.Select(item => item is null ? null : Canonical(item, definition: false))]);
      default:
        return node?.DeepClone();
    }
  }

  static void WriteSorted(Utf8JsonWriter writer, JsonNode node)
  {
    switch (node)
    {
      case JsonObject schema:
        writer.WriteStartObject();
        foreach (var (name, value) in schema.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
          writer.WritePropertyName(name);
          WriteSorted(writer, value);
        }

        writer.WriteEndObject();
        break;
      case JsonArray items:
        writer.WriteStartArray();
        foreach (var item in items)
          WriteSorted(writer, item);

        writer.WriteEndArray();
        break;
      case null:
        writer.WriteNullValue();
        break;
      default:
        node.WriteTo(writer);
        break;
    }
  }

  // The dotted names of one section, as nested objects with method signatures at the leaves.
  sealed class Group
  {
    readonly SortedDictionary<string, Group> Children = new(StringComparer.Ordinal);
    string Signature;

    public bool IsEmpty => Children.Count == 0;

    public void Add(string name, string signature)
    {
      var group = this;
      var segments = name.Split('.');
      for (var i = 0; i < segments.Length; i++)
      {
        if (group.Signature is not null)
          throw new InvalidOperationException($"'{string.Join('.', segments[..i])}' is both an operation and a group of '{name}', which TypeScript cannot express. Rename one of them.");

        if (!group.Children.TryGetValue(segments[i], out var child))
          group.Children[segments[i]] = child = new Group();
        group = child;
      }

      if (group.Signature is not null || group.Children.Count > 0)
        throw new InvalidOperationException($"'{name}' is both an operation and a group, which TypeScript cannot express. Rename one of them.");

      group.Signature = signature;
    }

    public void Write(StringBuilder typeScript, string name, string indent)
    {
      typeScript.Append(CultureInfo, $"{indent}{name}: {{\n");
      foreach (var (childName, child) in Children)
      {
        if (child.Signature is not null)
          typeScript.Append(CultureInfo, $"{indent}  {child.Signature}\n");
        else
          child.Write(typeScript, childName, indent + "  ");
      }

      typeScript.Append(CultureInfo, $"{indent}}};\n");
    }
  }
}
